"""
Results Exporter
----------------
Saves the outputs of all pipeline layers to disk in two complementary
forms:

    1. Structured JSON/CSV — detailed, per-layer/per-run, meant for
       programmatic reload (e.g. re-plotting without re-running the
       pipeline). Numbers are never rounded away here beyond what the
       producing layer already rounded.
    2. `report.md` — a single narrative Markdown report meant to be
       read (by a person or handed to an LLM) alongside the JSON. It
       states plainly, at the top, that every number in it is computed
       by deterministic statistical methods and must be treated as
       ground truth, while explicitly inviting hypothesis-generation
       about unlabeled columns and root causes — clearly marked as
       interpretation, not fact.

Lives in `utils/` rather than alongside the layer modules because it's
a cross-cutting I/O concern (it knows about all four layers' output
shapes) rather than an analysis layer itself.

Generic by design: nothing here assumes a specific dataset, column
names, or label schema — it reflects back whatever the layers produced.

Each dataset's output lives in its own subfolder, named after the
dataset (see ResultsExporter.__init__ / for_dataset_file), so running
the pipeline against several different datasets never overwrites a
previous run's results:

Output structure:
    analysis_output/<dataset_name>/
    ├── dataset_meta.json              # Layer 0 metadata + label summary
    ├── report.md                      # narrative report (see above)
    ├── layer1/
    │   ├── summary.json               # compact cross-run column stats
    │   └── run_{id}_profile.json      # native ydata-profiling JSON
    ├── layer2/
    │   ├── correlations_{method}.csv  # pooled correlation matrices
    │   ├── causal_per_run.json        # analyze_per_run() aggregated output
    │   ├── causal_legacy.json         # analyze() legacy output
    │   └── clusters.json              # cluster_columns() output
    ├── layer3/
    │   ├── drift_summary.json         # run_summary + per-run summaries
    │   └── run_{id}/
    │       ├── statistical.json       # per-variable statistical drift
    │       └── cusum.json             # per-variable onset detail
    ├── layer4/
    │   └── llm_inference.json         # Layer 4: LLM column-identity/root-cause output
    ├── audit_log.jsonl                # every external model call: what, to which
    │                                   model, why (see utils/audit_log.py)
    ├── run_data/
    │   ├── run_{id}.csv               # raw per-run values, for re-plotting
    │   └── columns.json
    └── cross_run/
        └── comparison_run{A}_vs_run{B}.json
"""

import os
import json
import numpy as np
import pandas as pd
from typing import Dict, Any, List, Optional
from collections import defaultdict
from datetime import datetime

try:
    from ydata_profiling import ProfileReport
except ImportError:
    ProfileReport = None


class NumpyEncoder(json.JSONEncoder):
    """JSON encoder that handles numpy types."""

    def default(self, obj):
        if isinstance(obj, (np.integer,)):
            return int(obj)
        if isinstance(obj, (np.floating,)):
            return float(obj)
        if isinstance(obj, np.ndarray):
            return obj.tolist()
        if isinstance(obj, np.bool_):
            return bool(obj)
        if isinstance(obj, pd.Timestamp):
            return obj.isoformat()
        if isinstance(obj, set):
            return list(obj)
        return super().default(obj)


LLM_INSTRUCTIONS_BLOCK = """> **Note for AI/LLM readers:** every number, table, and finding below was
> computed by deterministic statistical methods (each method and its
> threshold are named in context) — none of it was generated by a language
> model. Treat all reported values as ground truth: do not alter,
> recompute, or "correct" them.
>
> You may use this report to:
> - Hypothesize what an unlabeled column physically represents, based on
>   its statistical behavior, correlations, and causal relationships to
>   other columns.
> - Propose root-cause narratives for detected drift/anomalies, using the
>   onset ordering, causal graph, and correlation structure as evidence.
>
> Any such hypothesis or narrative must be clearly labeled as
> interpretation, not fact, and must not introduce numeric values,
> correlations, or statistics that do not appear in this report."""


class ResultsExporter:
    """
    Exports pipeline results to files.

    Output is namespaced per dataset (analysis_output/<dataset_name>/)
    so re-running the pipeline against a different dataset never
    overwrites a previous dataset's results.

    Usage:
        exporter = ResultsExporter("te_process_normal")
        # or, deriving the name from the file Layer 0 loaded:
        exporter = ResultsExporter.for_dataset_file(metadata["filepath"])

        exporter.export_dataset_meta(metadata, labels)
        exporter.export_layer1(run_id, profile_report)
        exporter.export_layer1_summary(run_descriptions)
        exporter.export_layer2_correlations(pooled_correlations)
        exporter.export_layer2_causal(aggregated)
        exporter.export_layer2_clusters(clusters)
        exporter.export_layer3_drift(drift_results)
        exporter.write_report(metadata, run_descriptions, ...)
    """

    def __init__(self, dataset_name: str, base_dir: str = "analysis_output"):
        """
        Parameters
        ----------
        dataset_name : str
            Name for this dataset's output subfolder. May be a plain
            name ("te_process_normal") or a raw file path — path
            components and the extension are stripped automatically,
            so passing metadata["filepath"] directly also works.
        base_dir : str
            Common parent directory under which every dataset gets its
            own subfolder.
        """
        self.dataset_name = self._sanitize_name(dataset_name)
        self.output_dir = os.path.join(base_dir, self.dataset_name)
        os.makedirs(self.output_dir, exist_ok=True)

    @classmethod
    def for_dataset_file(cls, filepath: str, base_dir: str = "analysis_output") -> "ResultsExporter":
        """Convenience constructor: derive dataset_name from a data file's path."""
        return cls(filepath, base_dir=base_dir)

    @staticmethod
    def _sanitize_name(name: str) -> str:
        """Turn a name or file path into a safe, extension-free directory name."""
        name = os.path.basename(str(name).rstrip("/\\"))
        stem, _ext = os.path.splitext(name)
        stem = stem or name
        safe = "".join(c if c.isalnum() or c in "-_." else "_" for c in stem)
        return safe.strip("_.") or "dataset"

    def _path(self, *parts: str) -> str:
        """Build a path under output_dir, creating parent dirs as needed."""
        filepath = os.path.join(self.output_dir, *parts)
        os.makedirs(os.path.dirname(filepath), exist_ok=True)
        return filepath

    def _write_json(self, filepath: str, data: Any):
        """Write data to a JSON file with numpy-safe encoding."""
        with open(filepath, "w") as f:
            json.dump(data, f, indent=2, cls=NumpyEncoder)

    @staticmethod
    def _fmt(x: Any) -> str:
        """Format a value for markdown: thousands separators for large
        ints, a few significant digits for floats, str() otherwise."""
        if x is None:
            return "?"
        if isinstance(x, bool):
            return str(x)
        if isinstance(x, (int, np.integer)):
            return f"{int(x):,}"
        if isinstance(x, (float, np.floating)):
            return f"{float(x):,.4g}"
        return str(x)

    # ═══════════════════════════════════════════════════════════════════
    # Dataset metadata (Layer 0)
    # ═══════════════════════════════════════════════════════════════════

    def export_dataset_meta(self, metadata: Dict[str, Any],
                            labels: Optional[pd.DataFrame] = None):
        """
        Save dataset-level metadata. Generic over whatever label/run/
        sample columns Layer 0 detected — no dataset-specific column
        names assumed.
        """
        meta = dict(metadata)
        meta["exported_at"] = datetime.now().isoformat()

        if labels is not None and len(labels) > 0:
            run_col = metadata.get("run_col")
            sample_col = metadata.get("sample_col")
            skip = {run_col, sample_col} - {None}

            label_summary = {}
            for col in labels.columns:
                if col in skip:
                    continue
                series = labels[col]
                n_unique = int(series.nunique())
                entry = {"dtype": str(series.dtype), "n_unique": n_unique}
                if n_unique <= 50:
                    entry["value_counts"] = {
                        str(k): int(v)
                        for k, v in series.value_counts().head(50).items()
                    }
                label_summary[col] = entry

            if run_col and run_col in labels.columns:
                label_summary.setdefault(run_col, {})
                label_summary[run_col]["n_runs"] = int(labels[run_col].nunique())

            meta["label_summary"] = label_summary

        self._write_json(self._path("dataset_meta.json"), meta)

    # ═══════════════════════════════════════════════════════════════════
    # Layer 1: statistical profiling
    # ═══════════════════════════════════════════════════════════════════

    def export_layer1(self, run_id: Any, report: "ProfileReport"):
        """
        Export one run's profile using ydata-profiling's native
        to_file(). Output is the library's exact JSON format — no
        fields added or removed.
        """
        filepath = self._path("layer1", f"run_{run_id}_profile.json")
        report.to_file(filepath)

    def export_layer1_summary(self, run_descriptions: Dict[Any, Any]):
        """
        Compact cross-run column-statistics table, distilled from each
        run's ydata-profiling description. Meant for quick reload
        (plotting, LLM context) without parsing the full native JSON
        dumps written by export_layer1().

        Parameters
        ----------
        run_descriptions : dict
            {run_id: desc} where desc = report.get_description()
        """
        runs_out = {}
        for run_id, desc in run_descriptions.items():
            variables = getattr(desc, "variables", {}) or {}
            alerts = getattr(desc, "alerts", []) or []
            table = getattr(desc, "table", {}) or {}
            n_rows = (
                table.get("n") if isinstance(table, dict)
                else getattr(table, "n", None)
            )

            var_out = {}
            for col, v in variables.items():
                stats = {
                    k: v.get(k) for k in (
                        "mean", "std", "min", "max", "skewness",
                        "kurtosis", "n_missing", "n_distinct",
                    )
                    if v.get(k) is not None
                }
                if stats:
                    var_out[col] = stats

            runs_out[str(run_id)] = {
                "n_rows": n_rows,
                "n_columns": len(variables),
                "n_alerts": len(alerts),
                "alerts": [str(a) for a in alerts],
                "variables": var_out,
            }

        self._write_json(self._path("layer1", "summary.json"), {"runs": runs_out})

    def export_layer1_pooled_profile(self, desc: Any):
        """
        Rich per-column descriptive stats from a SINGLE ydata-profiling
        description computed on data pooled across runs (concatenate
        the sampled runs, then call StatisticalProfiler.profile() once
        on the combined DataFrame — profile() itself doesn't need to
        know "runs" is a concept; pooling is the caller's job).

        This is deliberately richer than export_layer1_summary's
        per-run table (which only keeps mean/std/min/max/skew/kurtosis/
        missing/distinct): it's meant to answer "what does normal look
        like overall" for a dashboard — the natural place for that
        question, since Layer 3's own baseline is likewise defined as
        pooled-across-runs, not any single run.
        """
        variables = getattr(desc, "variables", {}) or {}
        alerts = getattr(desc, "alerts", []) or []

        alerts_by_column: Dict[str, list] = {}
        for a in alerts:
            col = getattr(a, "column_name", None)
            if col:
                alerts_by_column.setdefault(col, []).append(str(getattr(a, "alert_type", a)).replace("AlertType.", ""))

        fields = (
            "n_distinct", "p_distinct", "n_missing", "p_missing",
            "n_infinite", "p_infinite", "n_zeros", "p_zeros",
            "n_negative", "p_negative", "mean", "std", "min", "max",
            "skewness", "kurtosis", "memory_size",
        )
        columns_out = {}
        for col, v in variables.items():
            columns_out[col] = {
                **{k: v.get(k) for k in fields if v.get(k) is not None},
                "alerts": alerts_by_column.get(col, []),
            }

        self._write_json(self._path("layer1", "pooled_profile.json"), {"columns": columns_out})

    def export_layer1_quality(self, quality_by_run: Dict[Any, Any]):
        """
        Layer 1's data-quality check results (utils/data_quality.py)
        for each analyzed run — the missing-values check plus any
        operator-authored custom rules, and the trust verdict, run on
        the raw data itself before (i.e. independent of) any
        statistical profiling conclusions.
        """
        self._write_json(
            self._path("layer1", "data_quality.json"),
            {str(rid): q for rid, q in quality_by_run.items()},
        )

    # ═══════════════════════════════════════════════════════════════════
    # Layer 2: correlation, causal analysis, clustering
    # ═══════════════════════════════════════════════════════════════════

    def export_layer2_correlations(self, pooled_correlations: Dict[str, pd.DataFrame]):
        """Save pooled correlation matrices as CSV files."""
        for method, corr_df in pooled_correlations.items():
            corr_df.to_csv(self._path("layer2", f"correlations_{method}.csv"))

    def export_layer2_causal(self, aggregated: Dict[str, Any]):
        """Export analyze_per_run() aggregated causal results."""
        output = {
            "link_frequency": aggregated.get("link_frequency", {}),
            "mean_val": aggregated.get("mean_val", {}),
            "mean_pval": aggregated.get("mean_pval", {}),
            "lag_profiles": aggregated.get("lag_profiles", {}),
            "per_run_results": aggregated.get("per_run_results", []),
            "var_names": aggregated.get("var_names", []),
            "n_runs": aggregated.get("n_runs", 0),
            "metadata": aggregated.get("metadata", {}),
        }
        self._write_json(self._path("layer2", "causal_per_run.json"), output)

    def export_layer2_causal_legacy(self, pcmci_results: Dict[str, Any]):
        """Export analyze() legacy concatenated PCMCI results."""
        output = {}
        if "val_matrix" in pcmci_results:
            output["val_matrix"] = pcmci_results["val_matrix"]
        if "p_matrix" in pcmci_results:
            output["p_matrix"] = pcmci_results["p_matrix"]
        if pcmci_results.get("graph") is not None:
            output["graph"] = pcmci_results["graph"]
        output["var_names"] = pcmci_results.get("var_names", [])
        output["metadata"] = pcmci_results.get("metadata", {})
        self._write_json(self._path("layer2", "causal_legacy.json"), output)

    def export_layer2_clusters(self, clusters: Dict[str, Any]):
        """
        Export cluster_columns() output. The linkage matrix is kept
        (as a plain nested list) so a dendrogram can be redrawn later
        without recomputing clustering.
        """
        self._write_json(self._path("layer2", "clusters.json"), clusters)

    # ═══════════════════════════════════════════════════════════════════
    # Layer 3: drift and anomaly detection
    # ═══════════════════════════════════════════════════════════════════

    def export_layer3_drift(self, drift_results: Dict[str, Any]):
        """
        Export Layer 3 drift detection results: data quality, statistical,
        correlation, causal, and CUSUM onset drift.

        Per-variable detail (statistical and CUSUM) is written to
        separate per-run files to keep the main summary file small.
        Note run_summary (below) already carries each run's data-quality
        *verdict* (data_quality_gate/data_quality) inline since that's
        computed once and merged in by Layer 3 itself; this adds the
        full per-check detail (missing values + custom rule violations)
        behind it for anyone digging into why a run was gated.
        """
        main_output = {
            "run_summary": drift_results.get("run_summary", {}),
            "data_quality": drift_results.get("data_quality", {}),
            "metadata": drift_results.get("metadata", {}),
            "baseline": drift_results.get("baseline", {}),
        }

        stat = drift_results.get("statistical", {})
        main_output["statistical_summary"] = {
            rid: {
                "n_mean_drifted": d["n_mean_drifted"],
                "n_var_drifted": d["n_var_drifted"],
                "n_variables": d["n_variables"],
                "fraction_mean_drifted": d["fraction_mean_drifted"],
                "fraction_var_drifted": d["fraction_var_drifted"],
            }
            for rid, d in stat.get("per_run", {}).items()
        }
        main_output["statistical_thresholds"] = {
            "z_critical": stat.get("z_critical"),
            "alpha_bonferroni_mean": stat.get("alpha_bonferroni_mean"),
            "alpha_bonferroni_var": stat.get("alpha_bonferroni_var"),
        }

        corr = drift_results.get("correlation", {})
        if corr.get("status") == "ok":
            main_output["correlation_drift"] = {
                rid: {
                    "frobenius_norm": d["frobenius_norm"],
                    "frobenius_normalized": d["frobenius_normalized"],
                    "n_drifted_pairs": d["n_drifted_pairs"],
                    "n_total_pairs": d["n_total_pairs"],
                    "fraction_drifted": d["fraction_drifted"],
                    "top_drifted_pairs": d.get("top_drifted_pairs", [])[:10],
                }
                for rid, d in corr.get("per_run", {}).items()
            }
        else:
            main_output["correlation_drift"] = corr

        causal = drift_results.get("causal", {})
        if causal.get("status") == "ok":
            main_output["causal_drift"] = {
                "n_consensus_links": causal["n_consensus_links"],
                "n_total_unique_links": causal["n_total_unique_links"],
                "n_non_consensus": causal["n_non_consensus"],
                "consensus_threshold": causal["consensus_threshold"],
                "consensus_links": causal.get("consensus_links", [])[:30],
                "non_consensus_links": causal.get("non_consensus_links", [])[:30],
            }
        else:
            main_output["causal_drift"] = causal

        cusum = drift_results.get("cusum", {})
        if cusum.get("status") == "ok":
            main_output["cusum_onset"] = {
                "k": cusum.get("k"),
                "h": cusum.get("h"),
                "shift_sigma": cusum.get("shift_sigma"),
                "target_arl0_family_wise": cusum.get("target_arl0_family_wise"),
                "effective_arl0_per_channel": cusum.get("effective_arl0_per_channel"),
                "per_run": {
                    rid: {
                        "n_onset_detected": d["n_onset_detected"],
                        "fraction_onset_detected": d["fraction_onset_detected"],
                        "earliest_onset_sample": d["earliest_onset_sample"],
                        "earliest_onset_variable": d["earliest_onset_variable"],
                        "propagation_order": d["propagation_order"],
                    }
                    for rid, d in cusum.get("per_run", {}).items()
                },
            }
        else:
            main_output["cusum_onset"] = cusum

        self._write_json(self._path("layer3", "drift_summary.json"), main_output)

        for rid, d in stat.get("per_run", {}).items():
            self._write_json(
                self._path("layer3", f"run_{rid}", "statistical.json"),
                d["variables"],
            )
        for rid, d in cusum.get("per_run", {}).items():
            self._write_json(
                self._path("layer3", f"run_{rid}", "cusum.json"),
                d["variables"],
            )

    # ═══════════════════════════════════════════════════════════════════
    # Layer 4: LLM inference (future)
    # ═══════════════════════════════════════════════════════════════════

    def export_layer4_llm(self, llm_result: Dict[str, Any]):
        """Export Layer 4 LLM-derived results (e.g. column identity inference)."""
        self._write_json(self._path("layer4", "llm_inference.json"), llm_result)

    def get_audit_logger(self):
        """
        Return an AuditLogger writing to this dataset's audit_log.jsonl
        — the append-only record of every external LLM call (what was
        sent, to which model, why) and any other system decision worth
        explaining. Pass this straight to LLMAnalyst(..., audit_logger=...).

        Kept as its own class in utils/audit_log.py (reusable/testable
        on its own, without needing a ResultsExporter instance); this
        method only decides *where* its file lives, consistent with
        every other output path in this class.
        """
        from .audit_log import AuditLogger
        return AuditLogger(self._path("audit_log.jsonl"))

    # ═══════════════════════════════════════════════════════════════════
    # Raw data for standalone plotting
    # ═══════════════════════════════════════════════════════════════════

    def export_run_data(self, runs: Dict[Any, pd.DataFrame], columns: List[str]):
        """
        Save run DataFrames as CSV files so plotting can reload them
        without re-running the pipeline.
        """
        for run_id, df in runs.items():
            df[columns].to_csv(self._path("run_data", f"run_{run_id}.csv"))

        self._write_json(self._path("run_data", "columns.json"), columns)

    # ═══════════════════════════════════════════════════════════════════
    # Cross-run comparison
    # ═══════════════════════════════════════════════════════════════════

    def export_cross_run_comparison(self, run_a: Any, run_b: Any, desc_a, desc_b):
        """
        Compare two runs using their ydata-profiling descriptions.

        Parameters
        ----------
        desc_a, desc_b : ydata-profiling description objects
            From report.get_description()
        """
        comparison = {}
        vars_a = desc_a.variables
        vars_b = desc_b.variables

        for col_name in vars_a:
            if col_name not in vars_b:
                continue

            va, vb = vars_a[col_name], vars_b[col_name]
            mean_a, mean_b = va.get("mean"), vb.get("mean")
            std_a, std_b = va.get("std"), vb.get("std")

            if mean_a is None or mean_b is None or std_a is None:
                continue

            mean_shift = abs(mean_b - mean_a) / (std_a + 1e-12)
            var_ratio = (std_b ** 2) / (std_a ** 2 + 1e-12) if std_b else 0

            comparison[col_name] = {
                "mean_a": round(float(mean_a), 4),
                "mean_b": round(float(mean_b), 4),
                "mean_shift_sigma": round(float(mean_shift), 3),
                "std_a": round(float(std_a), 4),
                "std_b": round(float(std_b), 4) if std_b else None,
                "variance_ratio": round(float(var_ratio), 3),
                "skew_a": round(float(va.get("skewness", 0)), 3),
                "skew_b": round(float(vb.get("skewness", 0)), 3),
                "drifted": mean_shift > 3.0 or var_ratio > 2.0 or var_ratio < 0.5,
            }

        drifted = sorted(
            [(c, v) for c, v in comparison.items() if v.get("drifted")],
            key=lambda x: x[1]["mean_shift_sigma"],
            reverse=True,
        )

        output = {
            "run_a": run_a,
            "run_b": run_b,
            "n_columns": len(comparison),
            "n_drifted": len(drifted),
            "drifted_columns": [c for c, _ in drifted],
            "all_columns": comparison,
        }

        filename = f"comparison_run{run_a}_vs_run{run_b}.json"
        self._write_json(self._path("cross_run", filename), output)
        return output

    # ═══════════════════════════════════════════════════════════════════
    # Narrative report (report.md) — the LLM/human-facing deliverable
    # ═══════════════════════════════════════════════════════════════════

    def write_report(
        self,
        metadata: Dict[str, Any],
        run_descriptions: Optional[Dict[Any, Any]] = None,
        pooled_correlations: Optional[Dict[str, pd.DataFrame]] = None,
        clusters: Optional[Dict[str, Any]] = None,
        causal_aggregated: Optional[Dict[str, Any]] = None,
        drift_results: Optional[Dict[str, Any]] = None,
        top_k_anomalous: int = 10,
    ) -> str:
        """
        Write report.md — a single narrative report combining every
        layer's findings, meant to be read by a person or handed to an
        LLM for explanation/hypothesis-generation.

        All inputs are optional so a partial pipeline run still
        produces a (partial) report. See LLM_INSTRUCTIONS_BLOCK for
        the ground-rules stated at the top of the file: numbers are
        facts, everything else an LLM adds must be labeled hypothesis.

        Parameters
        ----------
        top_k_anomalous : int
            In self-check mode (baseline characterization, potentially
            hundreds of runs), only the top-k most anomalous runs get
            a full per-run detail section — otherwise the report would
            try to enumerate every run. In test mode (specific runs
            were scored against baseline), every scored run always
            gets full detail regardless of this limit.
        """
        lines = [
            "# Process Monitoring Analysis Report",
            "",
            f"_Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}_",
            "",
            LLM_INSTRUCTIONS_BLOCK,
            "",
        ]
        lines += self._report_dataset_section(metadata)
        lines += self._report_profiling_section(run_descriptions or {})
        lines += self._report_correlation_section(pooled_correlations, clusters)
        lines += self._report_causal_section(causal_aggregated)
        lines += self._report_drift_section(drift_results, top_k_anomalous)
        lines += self._report_file_index()

        text = "\n".join(lines)
        with open(self._path("report.md"), "w", encoding="utf-8") as f:
            f.write(text)
        return text

    def _report_dataset_section(self, metadata: Dict[str, Any]) -> List[str]:
        lines = ["## 1. Dataset Overview", ""]
        lines.append(f"- **File:** `{metadata.get('filename', 'unknown')}`")
        lines.append(
            f"- **Total rows:** {self._fmt(metadata.get('total_rows', metadata.get('n_rows')))}"
        )
        lines.append(f"- **Columns analyzed:** {self._fmt(metadata.get('n_columns'))}")
        lines.append(f"- **Runs:** {self._fmt(metadata.get('n_runs', 1))}")
        if metadata.get("label_columns"):
            lines.append(
                f"- **Label columns (excluded from analysis):** "
                f"{', '.join(metadata['label_columns'])}"
            )
        for col, info in metadata.get("label_summary", {}).items():
            if "value_counts" in info:
                vc = ", ".join(
                    f"{k}={v}" for k, v in list(info["value_counts"].items())[:10]
                )
                lines.append(f"  - `{col}` ({info['n_unique']} unique): {vc}")
        lines.append("")
        return lines

    def _report_profiling_section(self, run_descriptions: Dict[Any, Any]) -> List[str]:
        lines = ["## 2. Column Profiling (Layer 1)", ""]
        if not run_descriptions:
            lines.append("_No profiling data provided._")
            lines.append("")
            return lines

        n_runs = len(run_descriptions)
        lines.append(
            f"Profiled {n_runs} run(s) with ydata-profiling (full detail in "
            f"`layer1/summary.json` and `layer1/run_*_profile.json`)."
        )
        lines.append("")

        alert_counts = defaultdict(int)
        for desc in run_descriptions.values():
            for a in getattr(desc, "alerts", []) or []:
                alert_counts[str(a)] += 1

        if alert_counts:
            lines.append(f"**Most frequent data-quality alerts** (out of {n_runs} run(s)):")
            top_alerts = sorted(alert_counts.items(), key=lambda x: x[1], reverse=True)
            for alert, count in top_alerts[:15]:
                lines.append(f"- ({count}/{n_runs}) {alert}")
            lines.append("")

        # Full per-column table only when there are few runs — otherwise
        # this section would try to enumerate hundreds of runs.
        if n_runs <= 5:
            for run_id, desc in run_descriptions.items():
                variables = getattr(desc, "variables", {}) or {}
                lines.append(f"### Run {run_id}")
                lines.append("")
                lines.append("| Column | Mean | Std | Min | Max | Skew |")
                lines.append("|---|---|---|---|---|---|")
                for col, v in variables.items():
                    if v.get("mean") is None:
                        continue
                    lines.append(
                        f"| {col} | {self._fmt(v.get('mean'))} | {self._fmt(v.get('std'))} | "
                        f"{self._fmt(v.get('min'))} | {self._fmt(v.get('max'))} | "
                        f"{self._fmt(v.get('skewness'))} |"
                    )
                lines.append("")
        return lines

    def _report_correlation_section(
        self,
        pooled_correlations: Optional[Dict[str, pd.DataFrame]],
        clusters: Optional[Dict[str, Any]],
    ) -> List[str]:
        lines = ["## 3. Correlation Structure & Column Clusters (Layer 2)", ""]

        if pooled_correlations:
            for method, corr_df in pooled_correlations.items():
                cols = corr_df.columns.tolist()
                pairs = [
                    (cols[i], cols[j], corr_df.iloc[i, j])
                    for i in range(len(cols))
                    for j in range(i + 1, len(cols))
                    if pd.notna(corr_df.iloc[i, j])
                ]
                pairs.sort(key=lambda x: abs(x[2]), reverse=True)
                lines.append(f"**Strongest {method} correlations:**")
                for a, b, r in pairs[:15]:
                    lines.append(f"- `{a}` ↔ `{b}`: r = {r:.3f}")
                lines.append("")
        else:
            lines.append("_No correlation data provided._")
            lines.append("")

        if clusters and clusters.get("status") == "ok":
            lines.append(
                f"**Column clusters** (via `{clusters.get('correlation_method')}` "
                f"correlation, k={clusters.get('best_k')}, "
                f"silhouette={clusters.get('best_silhouette')}):"
            )
            for cid, cols in clusters.get("clusters", {}).items():
                lines.append(f"- Cluster {cid}: {', '.join(cols)}")
            if clusters.get("dropped_columns"):
                lines.append(
                    f"- Excluded (undefined correlation): "
                    f"{', '.join(clusters['dropped_columns'])}"
                )
            lines.append("")
        elif clusters:
            lines.append(f"_Clustering skipped: {clusters.get('reason', 'unknown')}._")
            lines.append("")

        return lines

    def _report_causal_section(self, causal_aggregated: Optional[Dict[str, Any]]) -> List[str]:
        lines = ["## 4. Causal Relationships (Layer 2 — PCMCI)", ""]
        if not causal_aggregated:
            lines.append("_No causal analysis provided._")
            lines.append("")
            return lines

        meta = causal_aggregated.get("metadata", {})
        params = meta.get("parameters", {})
        n_runs = causal_aggregated.get("n_runs", "?")
        lines.append(
            f"PCMCI run independently per run (tau_max={params.get('tau_max')}, "
            f"pc_alpha={params.get('pc_alpha')}, alpha_level={params.get('alpha_level')}), "
            f"aggregated across {n_runs} run(s)."
        )
        lines.append("")

        link_freq = causal_aggregated.get("link_frequency", {})
        mean_val = causal_aggregated.get("mean_val", {})
        sorted_links = sorted(link_freq.items(), key=lambda x: x[1], reverse=True)

        lines.append(f"**Top causal links** (out of {len(sorted_links)} unique links found):")
        lines.append("")
        lines.append("| Source | Target | Lag | Detected | Mean \\|parcorr\\| |")
        lines.append("|---|---|---|---|---|")
        for key, count in sorted_links[:20]:
            src, tgt, tau = key.split("|")
            val = abs(mean_val.get(key, 0))
            lines.append(f"| `{src}` | `{tgt}` | t-{tau} | {count}/{n_runs} | {val:.3f} |")
        lines.append("")
        return lines

    def _report_drift_section(
        self,
        drift_results: Optional[Dict[str, Any]],
        top_k_anomalous: int,
    ) -> List[str]:
        lines = ["## 5. Drift & Anomaly Detection (Layer 3)", ""]
        if not drift_results:
            lines.append("_No drift analysis provided._")
            lines.append("")
            return lines

        meta = drift_results.get("metadata", {})
        thresholds = meta.get("thresholds", {})
        mode = meta.get("mode", "?")

        lines.append(
            f"Mode: **{mode}** — {self._fmt(meta.get('n_baseline_runs'))} baseline run(s), "
            f"{self._fmt(meta.get('n_test_runs'))} scored run(s)."
        )
        lines.append(
            f"Thresholds: stat_alpha={thresholds.get('stat_alpha')}, "
            f"var_alpha={thresholds.get('var_alpha')}, "
            f"corr_alpha={thresholds.get('corr_alpha')}, "
            f"consensus_threshold={thresholds.get('consensus_threshold')}, "
            f"cusum_shift_sigma={thresholds.get('cusum_shift_sigma')}, "
            f"cusum_arl0={thresholds.get('cusum_arl0_family_wise')}"
        )
        lines.append("")

        run_summary = drift_results.get("run_summary", {})
        ranked = sorted(
            run_summary.items(),
            key=lambda kv: kv[1].get("anomaly_score", 0),
            reverse=True,
        )
        n_vars = meta.get("n_variables", "?")

        lines.append(
            f"**Ranked by anomaly score** (showing top "
            f"{min(len(ranked), top_k_anomalous)} of {len(ranked)}):"
        )
        lines.append("")
        lines.append(
            "| Run | Anomaly score | Mean-drifted | Var-drifted | "
            "Corr-drifted | Earliest onset |"
        )
        lines.append("|---|---|---|---|---|---|")
        for rid, rs in ranked[:top_k_anomalous]:
            onset = rs.get("earliest_onset_sample")
            onset_var = rs.get("earliest_onset_variable")
            onset_str = f"sample {onset} (`{onset_var}`)" if onset is not None else "none"
            lines.append(
                f"| {rid} | {rs.get('anomaly_score', 0):.4f} | "
                f"{rs.get('n_mean_drifted', 0)}/{n_vars} | "
                f"{rs.get('n_var_drifted', 0)}/{n_vars} | "
                f"{rs.get('frac_corr_drifted', 0):.1%} | {onset_str} |"
            )
        lines.append("")

        # Full detail: every explicitly-scored test run always gets one;
        # in self-check mode (potentially hundreds of baseline runs),
        # only the most anomalous ones do.
        test_run_ids = set(meta.get("test_run_ids", []))
        detail_ids = test_run_ids if mode == "test" else {
            rid for rid, _ in ranked[:top_k_anomalous]
        }

        for rid in sorted(detail_ids, key=str):
            rs = run_summary.get(str(rid), run_summary.get(rid))
            if not rs:
                continue
            lines.append(f"### Run {rid} detail")
            lines.append("")
            lines.append(f"- Anomaly score: **{rs.get('anomaly_score', 0):.4f}**")

            top_mean = rs.get("top_mean_drifted", [])
            if top_mean:
                names = ", ".join(
                    f"`{t['variable']}` (z={t['z_score']:.1f})" for t in top_mean[:8]
                )
                lines.append(f"- Top mean-drifted variables: {names}")

            prop = rs.get("propagation_order", [])
            if prop:
                lines.append(
                    "- **Onset/propagation order** "
                    "(earliest first — candidate root-cause ordering):"
                )
                for idx, p in enumerate(prop[:10], 1):
                    lines.append(f"  {idx}. `{p['variable']}` — onset sample {p['onset_sample']}")
            lines.append("")

        causal = drift_results.get("causal", {})
        if causal.get("status") == "ok":
            pct = int(causal["consensus_threshold"] * 100)
            lines.append(
                f"**Causal drift note:** {causal['n_consensus_links']} consensus links "
                f"(appear in ≥{pct}% of baseline runs), "
                f"{causal['n_non_consensus']} non-consensus/unstable links. "
                f"_(Known limitation: this currently reflects the baseline's own causal "
                f"structure only, not a per-run comparison against the scored run.)_"
            )
            lines.append("")

        return lines

